def tables(text):
    """Yield each markdown table as (header, rows)."""
    block = []
    for line in text.splitlines() + [""]:
        if line.startswith("|"):
            block.append([c.strip() for c in line.strip().strip("|").split("|")])
        elif block:
            if len(block) > 2: yield block[0], block[2:]
            block = []

def table(text, first):
    return next((h, r) for h, r in tables(text) if h[0] == first)

def write(name, const, data):
    (out / name).write_text(f"/** Generated by tools/build-data.py from the repository markdown. Do not edit by hand. */\nexport const {const} = {json.dumps(data, ensure_ascii=False, separators=(",", ":"))};\n", encoding="utf-8")

