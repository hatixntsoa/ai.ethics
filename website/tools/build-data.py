# ---- Documents as structured blocks (headings, paragraphs, lists, tables, code) ----
def slug(s):
    s = re.sub(r"\[(.+?)\]\(.+?\)", r"\1", s); s = re.sub(r"[*`]", "", s)
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")

def blocks(text, prefix):
    """Parse markdown into blocks: h, p, ul, ol, table, code, quote. Heading ids are '<prefix>-<slug>'."""
    out, L, i, seen = [], text.split("\n"), 0, {}
    special = lambda l: l.startswith(("```", "#", "|", ">")) or re.match(r"\s*([-*]|\d+\.) ", l) or l.strip() == "---"
    while i < len(L):
        ln = L[i]
        if ln.startswith("```"):
            buf, j = [], i + 1
            while j < len(L) and not L[j].startswith("```"): buf.append(L[j]); j += 1
            out.append({"t": "code", "lang": ln[3:].strip(), "text": "\n".join(buf)}); i = j + 1; continue
        m = re.match(r"(#{1,6}) (.+)", ln)
        if m:
            base = f"{prefix}-{slug(m[2])}"; n = seen.get(base, 0); seen[base] = n + 1
            out.append({"t": "h", "l": len(m[1]), "text": m[2].strip(), "id": base + (f"-{n+1}" if n else "")}); i += 1; continue
        if ln.startswith("|"):
            rows = []
            while i < len(L) and L[i].startswith("|"): rows.append([c.strip() for c in L[i].strip().strip("|").split("|")]); i += 1
            out.append({"t": "table", "head": rows[0], "rows": rows[2:]}); continue
        if ln.startswith(">"):
            buf = []
            while i < len(L) and L[i].startswith(">"): buf.append(L[i].lstrip("> ").strip()); i += 1
            out.append({"t": "quote", "text": " ".join(buf)}); continue
        if re.match(r"\s*([-*]|\d+\.) ", ln):
            ordered, items = bool(re.match(r"\s*\d+\.", ln)), []
            while i < len(L) and (re.match(r"\s*([-*]|\d+\.) ", L[i]) or (L[i].startswith("  ") and L[i].strip() and items)):
                if re.match(r"\s*([-*]|\d+\.) ", L[i]): items.append(re.sub(r"^\s*([-*]|\d+\.) ", "", L[i]))
                else: items[-1] += " " + L[i].strip()
                i += 1
            out.append({"t": "ol" if ordered else "ul", "items": items}); continue
        if ln.strip() in ("", "---"): i += 1; continue
        buf = []
        while i < len(L) and L[i].strip() and not special(L[i]): buf.append(L[i].strip()); i += 1
        if not buf: i += 1; continue
        out.append({"t": "p", "text": " ".join(buf)})
    return out

def drop_between(bl, start_pat, end_pat):
    """Remove blocks from the heading matching start_pat up to (not including) the heading matching end_pat."""
    res, skipping = [], False
    for b in bl:
        if b["t"] == "h" and re.search(start_pat, b["text"]): skipping = True
        if b["t"] == "h" and end_pat and re.search(end_pat, b["text"]): skipping = False
        if not skipping: res.append(b)
    return res

def gantt(bl):
    """Parse the Mermaid gantt block into phases and replace it with a slot."""
    phases, out = [], []
    for b in bl:
        if b["t"] == "code" and b["lang"] == "mermaid" and b["text"].lstrip().startswith("gantt"):
            sec = ""
            for ln in b["text"].splitlines():
                ln = ln.strip()
                if ln.startswith("section "): sec = ln[8:]
                m = re.match(r"(P\d [^:]+?)\s*:(\w+), (\d{4})-(\d{2}), (\d+)M", ln)
                if m: phases.append({"id": m[2].upper(), "label": m[1].strip(), "section": sec, "start": f"{m[3]}-{m[4]}", "months": int(m[5])})
            out.append({"t": "slot", "name": "gantt", "phases": phases})
        elif b["t"] == "table" and b["head"][0] == "Activity":
            out.append({"t": "slot", "name": "raci", "head": [plain(x) for x in b["head"]], "rows": [[x for x in r] for r in b["rows"]]})
        elif b["t"] == "table" and b["head"][0] == "#" and "AI Act" in b["head"][1]:
            out.append({"t": "slot", "name": "matrix"})
        else: out.append(b)
    return out

